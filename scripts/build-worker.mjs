import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptsDir, "..");

const [html, css, javascript] = await Promise.all([
  readFile(path.join(root, "index.html"), "utf8"),
  readFile(path.join(root, "src/styles.css"), "utf8"),
  readFile(path.join(root, "src/main.js"), "utf8")
]);

const worker = `// Generated by scripts/build-worker.mjs. Edit the source files instead.
const assets = {
  "/": { body: ${JSON.stringify(html)}, type: "text/html; charset=UTF-8" },
  "/index.html": { body: ${JSON.stringify(html)}, type: "text/html; charset=UTF-8" },
  "/src/styles.css": { body: ${JSON.stringify(css)}, type: "text/css; charset=UTF-8" },
  "/src/main.js": { body: ${JSON.stringify(javascript)}, type: "text/javascript; charset=UTF-8" }
};

export default {
  async fetch(request) {
    if (request.method !== "GET" && request.method !== "HEAD") {
      return new Response("Method not allowed", { status: 405, headers: { Allow: "GET, HEAD" } });
    }

    const pathname = new URL(request.url).pathname;
    const asset = assets[pathname];

    if (!asset) {
      return new Response("Not found", { status: 404, headers: { "Content-Type": "text/plain; charset=UTF-8" } });
    }

    return new Response(request.method === "HEAD" ? null : asset.body, {
      status: 200,
      headers: {
        "Content-Type": asset.type,
        "Cache-Control": "no-cache",
        "X-Content-Type-Options": "nosniff",
        "Referrer-Policy": "strict-origin-when-cross-origin"
      }
    });
  }
};
`;

await writeFile(path.join(root, "worker.js"), worker);
console.log("Generated worker.js from index.html and src/.");
